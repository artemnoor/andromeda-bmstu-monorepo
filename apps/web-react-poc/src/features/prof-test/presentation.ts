export function categoryPresentation(category: SubjectCategory): { title: string; detail: string } {
  const copy = CATEGORY_COPY[category.name];
  return { title: copy?.[0] ?? category.name, detail: copy?.[1] ?? category.definition };
}

export function matchesProgramSearch(
  program: RankedCareerProfile["profile"]["program"],
  query: string,
): boolean {
  const terms = query.toLocaleLowerCase("ru").replaceAll("ё", "е").trim().split(/\s+/).filter(Boolean);
  const text = [program.name, program.code, program.directionCode, program.directionName,
    program.departmentCode, program.departmentName,
    ...(program.departments ?? []).flatMap((department) => [department.code, department.name])]
    .filter(Boolean).join(" ").toLocaleLowerCase("ru").replaceAll("ё", "е");
  return terms.every((term) => text.includes(term));
}
